//! 全部动作与快捷键（对标 Zed 的 macOS 默认键位）。
use gpui::{App, KeyBinding, actions};

actions!(
    editor,
    [
        MoveLeft, MoveRight, MoveUp, MoveDown, SelectLeft, SelectRight, SelectUp, SelectDown,
        MoveWordLeft, MoveWordRight, SelectWordLeft, SelectWordRight,
        MoveToLineStart, MoveToLineEnd, SelectToLineStart, SelectToLineEnd,
        MoveToDocStart, MoveToDocEnd, SelectToDocStart, SelectToDocEnd,
        PageUp, PageDown, SelectAll, Backspace, Delete, DeleteWordLeft, DeleteToLineStart, DeleteToLineEnd,
        Enter, Tab, Outdent, Undo, Redo, Copy, Cut, Paste, ToggleComment, DuplicateLine, MoveLineUp, MoveLineDown,
        DeleteLine, Escape, Newline, ToggleWrap, FoldAtCursor, UnfoldAtCursor, ReplaceCurrent, ReplaceAll, ShowCharacterPalette, FindInFile, FindNext, FindPrev, AcceptHunk, RejectHunk,
    ]
);

actions!(
    workspace,
    [
        Save, CloseTab, NextTab, PrevTab, QuickOpen, CommandPalette, ToggleSidebar, ToggleTerminal, ToggleAgent,
        FocusAgent, ProjectSearch, OpenFolder, InlineAssist, AcceptReview, RejectReview, NewThread, OpenSettings, Quit,
        ToggleTheme, FindReplace, ShowGit, ShowFiles, ApplyLatest, GotoSymbol, GotoLine, ShowOutline, GotoDefinition, ShowHover, TriggerCompletion, ShowProblems, SplitRight,
    ]
);

pub fn bind_keys(cx: &mut App) {
    cx.bind_keys([
        KeyBinding::new("left", MoveLeft, Some("Editor")),
        KeyBinding::new("right", MoveRight, Some("Editor")),
        KeyBinding::new("up", MoveUp, Some("Editor")),
        KeyBinding::new("down", MoveDown, Some("Editor")),
        KeyBinding::new("shift-left", SelectLeft, Some("Editor")),
        KeyBinding::new("shift-right", SelectRight, Some("Editor")),
        KeyBinding::new("shift-up", SelectUp, Some("Editor")),
        KeyBinding::new("shift-down", SelectDown, Some("Editor")),
        KeyBinding::new("alt-left", MoveWordLeft, Some("Editor")),
        KeyBinding::new("alt-right", MoveWordRight, Some("Editor")),
        KeyBinding::new("alt-shift-left", SelectWordLeft, Some("Editor")),
        KeyBinding::new("alt-shift-right", SelectWordRight, Some("Editor")),
        KeyBinding::new("cmd-left", MoveToLineStart, Some("Editor")),
        KeyBinding::new("cmd-right", MoveToLineEnd, Some("Editor")),
        KeyBinding::new("home", MoveToLineStart, Some("Editor")),
        KeyBinding::new("end", MoveToLineEnd, Some("Editor")),
        KeyBinding::new("cmd-shift-left", SelectToLineStart, Some("Editor")),
        KeyBinding::new("cmd-shift-right", SelectToLineEnd, Some("Editor")),
        KeyBinding::new("cmd-up", MoveToDocStart, Some("Editor")),
        KeyBinding::new("cmd-down", MoveToDocEnd, Some("Editor")),
        KeyBinding::new("cmd-shift-up", SelectToDocStart, Some("Editor")),
        KeyBinding::new("cmd-shift-down", SelectToDocEnd, Some("Editor")),
        KeyBinding::new("pageup", PageUp, Some("Editor")),
        KeyBinding::new("pagedown", PageDown, Some("Editor")),
        KeyBinding::new("cmd-a", SelectAll, Some("Editor")),
        KeyBinding::new("backspace", Backspace, Some("Editor")),
        KeyBinding::new("delete", Delete, Some("Editor")),
        KeyBinding::new("alt-backspace", DeleteWordLeft, Some("Editor")),
        KeyBinding::new("cmd-backspace", DeleteToLineStart, Some("Editor")),
        KeyBinding::new("ctrl-k", DeleteToLineEnd, Some("Editor")),
        KeyBinding::new("enter", Enter, Some("Editor")),
        KeyBinding::new("shift-enter", Newline, Some("Editor")),
        KeyBinding::new("tab", Tab, Some("Editor")),
        KeyBinding::new("shift-tab", Outdent, Some("Editor")),
        KeyBinding::new("cmd-z", Undo, Some("Editor")),
        KeyBinding::new("cmd-shift-z", Redo, Some("Editor")),
        KeyBinding::new("cmd-c", Copy, Some("Editor")),
        KeyBinding::new("cmd-x", Cut, Some("Editor")),
        KeyBinding::new("cmd-v", Paste, Some("Editor")),
        KeyBinding::new("cmd-/", ToggleComment, Some("Editor")),
        KeyBinding::new("cmd-shift-d", DuplicateLine, Some("Editor")),
        KeyBinding::new("alt-up", MoveLineUp, Some("Editor")),
        KeyBinding::new("alt-down", MoveLineDown, Some("Editor")),
        KeyBinding::new("cmd-shift-k", DeleteLine, Some("Editor")),
        KeyBinding::new("escape", Escape, Some("Editor")),
        KeyBinding::new("ctrl-cmd-space", ShowCharacterPalette, Some("Editor")),
        KeyBinding::new("cmd-f", FindInFile, Some("Editor")),
        KeyBinding::new("cmd-g", FindNext, Some("Editor")),
        KeyBinding::new("alt-z", ToggleWrap, Some("Editor")),
        KeyBinding::new("cmd-alt-[", FoldAtCursor, Some("Editor")),
        KeyBinding::new("cmd-alt-]", UnfoldAtCursor, Some("Editor")),
        KeyBinding::new("cmd-shift-g", FindPrev, Some("Editor")),
        // 工作区
        KeyBinding::new("cmd-s", Save, None),
        KeyBinding::new("cmd-w", CloseTab, None),
        KeyBinding::new("cmd-alt-right", NextTab, None),
        KeyBinding::new("cmd-alt-left", PrevTab, None),
        KeyBinding::new("cmd-p", QuickOpen, None),
        KeyBinding::new("cmd-shift-p", CommandPalette, None),
        KeyBinding::new("cmd-b", ToggleSidebar, None),
        KeyBinding::new("cmd-j", ToggleTerminal, None),
        KeyBinding::new("cmd-shift-a", ToggleAgent, None),
        KeyBinding::new("cmd-l", FocusAgent, None),
        KeyBinding::new("cmd-shift-f", ProjectSearch, None),
        KeyBinding::new("cmd-o", OpenFolder, None),
        KeyBinding::new("cmd-k", InlineAssist, Some("Editor")),
        KeyBinding::new("ctrl-enter", InlineAssist, Some("Editor")),
        KeyBinding::new("cmd-enter", AcceptReview, None),
        KeyBinding::new("cmd-backspace", RejectReview, Some("Review")),
        KeyBinding::new("cmd-,", OpenSettings, None),
        KeyBinding::new("cmd-q", Quit, None),
        KeyBinding::new("cmd-\\", SplitRight, None),
        KeyBinding::new("f12", GotoDefinition, Some("Editor")),
        KeyBinding::new("cmd-i", ShowHover, Some("Editor")),
        KeyBinding::new("ctrl-space", TriggerCompletion, Some("Editor")),
        KeyBinding::new("cmd-alt-f", FindReplace, None),
        KeyBinding::new("cmd-shift-o", GotoSymbol, None),
        KeyBinding::new("ctrl-g", GotoLine, None),
        KeyBinding::new("cmd-shift-enter", ApplyLatest, None),
        KeyBinding::new("cmd-shift-e", ShowFiles, None),
        KeyBinding::new("cmd-shift-g", ShowGit, Some("Workspace")),
    ]);
}
